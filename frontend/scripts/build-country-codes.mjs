
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, 'data', 'country-codes.csv');
const target = join(here, '..', 'src', 'data', 'countryCodes.js');


function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((v) => v !== ''));
}

const [header, ...data] = parseCsv(readFileSync(source, 'utf8').replace(/^﻿/, ''));
const col = (name) => {
  const i = header.indexOf(name);
  if (i === -1) throw new Error(`country-codes.csv has no "${name}" column`);
  return i;
};

const RENAME = { US: 'United States', GB: 'United Kingdom' };

const ISO = col('ISO3166-1-Alpha-2'), DIAL = col('Dial');
const SHORT = col('CLDR display name'), OFFICIAL = col('official_name_en');

const countries = data
  .map((r) => ({
    iso: r[ISO].trim(),
    name: (RENAME[r[ISO].trim()] || r[SHORT] || r[OFFICIAL]).trim(),

    dial: r[DIAL].split(',')[0].split('-')[0].replace(/\D/g, ''),
  }))
  .filter((c) => c.iso && c.name && c.dial)
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = countries.map((c) => `  { iso: ${JSON.stringify(c.iso)}, name: ${JSON.stringify(c.name)}, dial: ${JSON.stringify(c.dial)} },`);
writeFileSync(target, [
  '// Generated by scripts/build-country-codes.mjs from scripts/data/country-codes.csv.',
  '// Do not edit by hand: change the CSV and run `node scripts/build-country-codes.mjs`.',
  '/** Every country with its ISO code and telephone country code, by name. */',
  'const COUNTRY_CODES = [',
  ...lines,
  '];',
  '',
  'export default COUNTRY_CODES;',
  '',
].join('\n'));
console.log(`Wrote ${countries.length} countries to ${target}`);
